/**
 * Retrieval-augmented investigation assistant.
 *
 * <p>Pipeline: case facts (from Postgres and the live risk engine) + hybrid retrieval over the
 * policy and playbook knowledge base, then a grounded prompt that demands numbered citations. When no LLM
 * is configured (or it fails) the same retrieved evidence drives a deterministic, template-based
 * brief, so the feature degrades gracefully instead of disappearing.
 */
@Service
public class CopilotService {

    static final String SYSTEM_PROMPT = """
            You are FraudShield Copilot, an assistant for fraud investigators at an Indian bank.
            You write concise, factual investigation briefs and answers.

            Rules:
            - Use only the CASE FACTS and KNOWLEDGE passages provided. Do not invent facts, amounts, \
            regulations, deadlines or contact numbers.
            - Cite knowledge passages inline as [1], [2] using their numbers. Every regulatory or \
            procedural statement needs a citation.
            - If the evidence is inconclusive, say so and state what would resolve it.
            - Format money in Indian style with the ₹ symbol.
            - Be direct. Investigators are busy; no filler.""";

    static final String SUMMARY_INSTRUCTIONS = """
            Write an investigation brief in Markdown with exactly these sections:
            ### Summary
            (2-3 sentences: who, what, how much, how risky)
            ### Why it was flagged
            (bullets grounded in the risk signals)
            ### Likely typology
            (name the fraud pattern and justify it from the facts, with citations)
            ### Recommended next steps
            (numbered, concrete, from the playbooks, with citations)
            ### Regulatory obligations
            (bullets with citations; only what applies to this case)""";

    private static final NumberFormat INR = NumberFormat.getCurrencyInstance(Locale.of("en", "IN"));
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("dd MMM HH:mm")
            .withZone(ZoneId.of("Asia/Kolkata"));
    private static final Set<String> STOPWORDS = Set.of("the", "a", "an", "and", "or", "of", "to", "in", "on",
            "for", "is", "are", "was", "be", "it", "this", "that", "what", "how", "should", "do", "does", "i",
            "we", "my", "our", "with", "by", "at", "as", "can", "from", "if", "when", "which", "who", "why", "about",
            "under", "into", "any", "there", "their", "they", "them", "has", "have", "will", "would", "must");

    private final CaseService cases;
    private final CaseRepository repo;
    private final HybridRetriever retriever;
    private final LlmClient llm;
    private final RiskEngineClient risk;

    public CopilotService(CaseService cases, CaseRepository repo, HybridRetriever retriever, LlmClient llm,
                          RiskEngineClient risk) {
        this.cases = cases;
        this.repo = repo;
        this.retriever = retriever;
        this.llm = llm;
        this.risk = risk;
    }

    public CopilotModels.Answer summarize(long caseId, String requestedBy) {
        long start = System.currentTimeMillis();
        CaseModels.CaseDetail detail = cases.detail(caseId);
        Typology typology = Typology.valueOf(detail.kase().typology());
        Map<String, Object> intel = risk.account(detail.kase().subjectVpa());

        List<Passage> passages = retrieveForCase(detail, typology);
        String facts = caseFacts(detail, intel);
        String prompt = "CASE FACTS\n" + facts + "\n\nKNOWLEDGE\n" + knowledgeBlock(passages) + "\n\n"
                + SUMMARY_INSTRUCTIONS;

        var generated = llm.chat(SYSTEM_PROMPT, prompt);
        String text = generated.orElseGet(() -> fallbackSummary(detail, typology, intel, passages));
        String by = generated.isPresent() ? llm.description() : "rule-based fallback";
        repo.saveSummary(caseId, text, by);
        repo.addEvent(caseId, requestedBy, "AI_SUMMARY", "Investigation brief generated by " + by + " using "
                + passages.size() + " knowledge passages.");
        return new CopilotModels.Answer(text, citations(passages), by, generated.isPresent(),
                System.currentTimeMillis() - start);
    }

    public CopilotModels.Answer ask(String question, Long caseId) {
        if (question == null || question.isBlank()) throw new IllegalArgumentException("Question is required");
        long start = System.currentTimeMillis();
        String facts = "";
        String query = question;
        if (caseId != null) {
            CaseModels.CaseDetail detail = cases.detail(caseId);
            facts = caseFacts(detail, risk.account(detail.kase().subjectVpa()));
            query = question + " " + Typology.valueOf(detail.kase().typology()).label();
        }
        List<Passage> passages = retriever.search(query, 5);
        String prompt = (facts.isEmpty() ? "" : "CASE FACTS\n" + facts + "\n\n") + "KNOWLEDGE\n"
                + knowledgeBlock(passages) + "\n\nQUESTION\n" + question
                + "\n\nAnswer in at most 200 words of Markdown, citing passages as [n].";
        var generated = llm.chat(SYSTEM_PROMPT, prompt);
        String text = generated.orElseGet(() -> extractiveAnswer(question, passages));
        return new CopilotModels.Answer(text, citations(passages),
                generated.isPresent() ? llm.description() : "rule-based fallback", generated.isPresent(),
                System.currentTimeMillis() - start);
    }

    /** Two retrievals: one for the fraud pattern and playbook, one for the regulatory side. */
    List<Passage> retrieveForCase(CaseModels.CaseDetail d, Typology typology) {
        Set<String> codes = d.payments().stream().flatMap(p -> p.reasons().stream()).map(Reason::code)
                .collect(Collectors.toCollection(java.util.LinkedHashSet::new));
        String patternQuery = typology.label() + " investigation playbook triage containment " + String.join(" ", codes);
        String regulatoryQuery = typology.label()
                + " regulatory reporting obligations suspicious transaction report FIU-IND customer liability 1930";
        Map<Long, Passage> merged = new LinkedHashMap<>();
        retriever.search(patternQuery, 4).forEach(p -> merged.putIfAbsent(p.id(), p));
        retriever.search(regulatoryQuery, 3).forEach(p -> merged.putIfAbsent(p.id(), p));
        return new ArrayList<>(merged.values());
    }

    static String caseFacts(CaseModels.CaseDetail d, Map<String, Object> intel) {
        CaseModels.CaseRow c = d.kase();
        StringBuilder sb = new StringBuilder();
        sb.append("Case #").append(c.id()).append(" | subject account: ").append(c.subjectVpa())
                .append(" | pattern: ").append(d.typologyLabel())
                .append(" | priority: ").append(c.priority()).append(" | status: ").append(c.status())
                .append("\nHighest risk score: ").append(String.format("%.2f", c.riskScore()))
                .append(" | flagged payments: ").append(c.paymentCount())
                .append(" | total amount: ").append(INR.format(c.totalAmount())).append('\n');
        if (!d.payments().isEmpty()) {
            sb.append("\nFlagged payments (newest first):\n");
            d.payments().stream().limit(12).forEach(p -> sb.append("- ")
                    .append(TIME.format(p.paidAt().toInstant())).append(" IST: ")
                    .append(p.payerVpa()).append(" -> ").append(p.payeeVpa()).append(", ")
                    .append(INR.format(p.amount())).append(", ").append(p.decision())
                    .append(" (risk ").append(String.format("%.2f", p.riskScore())).append("), device ")
                    .append(p.deviceId()).append(". Signals: ")
                    .append(p.reasons().stream().limit(4).map(Reason::description).collect(Collectors.joining("; ")))
                    .append('\n'));
        }
        if (!intel.isEmpty()) {
            sb.append("\nLive account intelligence for ").append(c.subjectVpa()).append(":\n")
                    .append("- payments made: ").append(intel.get("paymentsMade"))
                    .append(", first seen: ").append(intel.get("firstSeen"))
                    .append(", deny-listed: ").append(intel.get("denylisted")).append('\n');
            if (intel.get("devices") instanceof List<?> devices) {
                sb.append("- devices used: ").append(devices.size()).append('\n');
            }
            if (intel.get("mule") instanceof Map<?, ?> mule) {
                sb.append("- mule score: ").append(mule.get("score")).append(", signals: ")
                        .append(mule.get("signals")).append('\n');
            }
        }
        List<CaseModels.CaseEvent> events = d.timeline();
        if (!events.isEmpty()) {
            sb.append("\nRecent timeline:\n");
            events.stream().skip(Math.max(0, events.size() - 6)).forEach(e -> sb.append("- ")
                    .append(e.eventType()).append(" by ").append(e.actor()).append(": ").append(e.message()).append('\n'));
        }
        return sb.toString();
    }

    static String knowledgeBlock(List<Passage> passages) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < passages.size(); i++) {
            Passage p = passages.get(i);
            sb.append('[').append(i + 1).append("] ").append(p.docTitle()).append(" - ").append(p.section())
                    .append('\n').append(p.content()).append("\n\n");
        }
        return sb.toString().trim();
    }

    static List<CopilotModels.Citation> citations(List<Passage> passages) {
        List<CopilotModels.Citation> out = new ArrayList<>();
        for (int i = 0; i < passages.size(); i++) {
            Passage p = passages.get(i);
            String snippet = p.content().length() > 320 ? p.content().substring(0, 317) + "..." : p.content();
            out.add(new CopilotModels.Citation(i + 1, p.docId(), p.docTitle(), p.section(), snippet, p.source(),
                    p.denseRank(), p.lexicalRank(), Math.round(p.rrfScore() * 10000) / 10000.0));
        }
        return out;
    }

    // ---------------------------------------------------------------- fallback (no LLM)

    String fallbackSummary(CaseModels.CaseDetail d, Typology typology, Map<String, Object> intel,
                           List<Passage> passages) {
        CaseModels.CaseRow c = d.kase();
        StringBuilder sb = new StringBuilder();
        sb.append("### Summary\n");
        sb.append("Case #").append(c.id()).append(" concerns **").append(c.subjectVpa()).append("** (")
                .append(d.typologyLabel().toLowerCase()).append("). ").append(c.paymentCount())
                .append(c.paymentCount() == 1 ? " payment" : " payments").append(" totalling ")
                .append(INR.format(c.totalAmount())).append(" were held or blocked");
        if (!d.payments().isEmpty()) {
            var times = d.payments().stream().map(p -> TIME.format(p.paidAt().toInstant())).sorted().toList();
            if (times.get(0).equals(times.get(times.size() - 1))) {
                sb.append(" at ").append(times.get(0)).append(" IST");
            } else {
                sb.append(" between ").append(times.get(0)).append(" and ").append(times.get(times.size() - 1))
                        .append(" IST");
            }
        }
        sb.append(". Highest risk score: ").append(String.format("%.2f", c.riskScore())).append(" (")
                .append(c.priority()).append(").\n\n");

        sb.append("### Why it was flagged\n");
        Map<String, Reason> strongest = new LinkedHashMap<>();
        d.payments().stream().flatMap(p -> p.reasons().stream())
                .sorted(Comparator.comparingDouble(Reason::contribution).reversed())
                .forEach(r -> strongest.putIfAbsent(r.code(), r));
        strongest.values().stream().limit(5).forEach(r -> sb.append("- **").append(r.code()).append("**: ")
                .append(r.description()).append('\n'));
        if (intel.get("mule") instanceof Map<?, ?> mule && mule.get("score") instanceof Number score
                && score.doubleValue() >= 0.3) {
            sb.append("- **Mule score ").append(String.format("%.2f", score.doubleValue()))
                    .append("** from the payment-graph analyser\n");
        }
        if (strongest.isEmpty()) sb.append("- Raised by the asynchronous mule-network analyser.\n");

        sb.append("\n### Likely typology\n");
        int typologyRef = indexOf(passages, p -> p.docId().startsWith("01-") && matchesTypology(p, typology));
        sb.append("**").append(d.typologyLabel()).append("**");
        if (typologyRef > 0) {
            sb.append(": ").append(firstSentences(passages.get(typologyRef - 1).content(), 2)).append(" [")
                    .append(typologyRef).append("]");
        }
        sb.append("\n\n### Recommended next steps\n");
        int stepRef = indexOf(passages, p -> p.docId().startsWith(playbookFor(typology)));
        List<String> steps = new ArrayList<>();
        if (stepRef > 0) steps.addAll(listItems(passages.get(stepRef - 1).content()));
        if (steps.isEmpty()) {
            // Retrieval didn't surface the playbook; read it directly.
            List<Passage> playbook = retriever.byDocument(playbookFor(typology) + playbookSuffix(typology));
            if (!playbook.isEmpty()) steps.addAll(listItems(playbook.get(0).content()));
        }
        int n = 1;
        for (String s : steps.stream().limit(5).toList()) {
            sb.append(n++).append(". ").append(s).append(stepRef > 0 ? " [" + stepRef + "]" : "").append('\n');
        }
        if (steps.isEmpty()) sb.append("1. Review the payment graph and contact the customer on registered details.\n");

        sb.append("\n### Regulatory obligations\n");
        int regs = 0;
        for (int i = 0; i < passages.size() && regs < 3; i++) {
            Passage p = passages.get(i);
            if (p.docId().startsWith("02-") || p.docId().startsWith("03-") || p.docId().startsWith("04-")) {
                sb.append("- ").append(firstSentences(p.content(), 1)).append(" [").append(i + 1).append("]\n");
                regs++;
            }
        }
        if (regs == 0) sb.append("- No regulatory passage retrieved; consult the compliance team.\n");
        sb.append("\n_Generated by the rule-based fallback from retrieved knowledge (LLM not configured or unavailable)._");
        return sb.toString();
    }

    static String extractiveAnswer(String question, List<Passage> passages) {
        Set<String> terms = tokens(question);
        record Scored(String sentence, int ref, double score) {
        }
        List<Scored> scored = new ArrayList<>();
        for (int i = 0; i < passages.size(); i++) {
            for (String sentence : passages.get(i).content().split("(?<=[.!?])\\s+(?=[A-Z(])|\\n+")) {
                String s = sentence.replaceFirst("^[-*\\d.\\s]+", "").trim();
                if (s.length() < 30) continue;
                Set<String> words = tokens(s);
                long overlap = words.stream().filter(terms::contains).count();
                // Earlier (higher-ranked) passages get a small boost.
                if (overlap > 0) scored.add(new Scored(s, i + 1, overlap + 0.3 * (passages.size() - i)));
            }
        }
        if (scored.isEmpty()) {
            return "I couldn't find anything in the knowledge base that answers this. Try rephrasing, or ask a "
                    + "compliance lead.\n\n_Rule-based fallback (LLM not configured or unavailable)._";
        }
        StringBuilder sb = new StringBuilder("Here is what the knowledge base says:\n\n");
        scored.stream().sorted(Comparator.comparingDouble(Scored::score).reversed()).limit(4)
                .forEach(s -> sb.append("- ").append(s.sentence()).append(" [").append(s.ref()).append("]\n"));
        sb.append("\n_Extractive answer from the rule-based fallback (LLM not configured or unavailable)._");
        return sb.toString();
    }

    private static Set<String> tokens(String text) {
        return Pattern.compile("[^a-z0-9]+").splitAsStream(text.toLowerCase())
                .filter(w -> w.length() > 2 && !STOPWORDS.contains(w))
                .map(w -> w.endsWith("s") && w.length() > 4 ? w.substring(0, w.length() - 1) : w)
                .collect(Collectors.toSet());
    }

    private static boolean matchesTypology(Passage p, Typology t) {
        String s = p.section().toLowerCase();
        return switch (t) {
            case MONEY_MULE -> s.contains("mule");
            case ACCOUNT_TAKEOVER -> s.contains("takeover");
            case ACCOUNT_PROBING -> s.contains("probing");
            case SOCIAL_ENGINEERING_SCAM -> s.contains("social");
            case SUSPICIOUS_ACTIVITY -> true;
        };
    }

    private static String playbookFor(Typology t) {
        return switch (t) {
            case ACCOUNT_TAKEOVER -> "06-";
            case SOCIAL_ENGINEERING_SCAM -> "07-";
            default -> "05-";
        };
    }

    private static String playbookSuffix(Typology t) {
        return switch (t) {
            case ACCOUNT_TAKEOVER -> "playbook-account-takeover";
            case SOCIAL_ENGINEERING_SCAM -> "playbook-scam-victim";
            default -> "playbook-money-mule";
        };
    }

    private static int indexOf(List<Passage> passages, java.util.function.Predicate<Passage> test) {
        for (int i = 0; i < passages.size(); i++) if (test.test(passages.get(i))) return i + 1;
        return -1;
    }

    static String firstSentences(String text, int count) {
        String flat = text.replaceAll("\\s*\\n\\s*[-*]\\s*", " ").replaceAll("\\s+", " ").trim();
        // A sentence ends at . ! or ? followed by whitespace and a capital (so "cybercrime.gov.in"
        // and "Rs. 5" stay intact), or at the end of the text.
        Matcher m = Pattern.compile(".+?[.!?](?=\\s+[A-Z(\"]|$)").matcher(flat);
        StringBuilder sb = new StringBuilder();
        int n = 0;
        while (m.find() && n < count) {
            sb.append(m.group().trim()).append(' ');
            n++;
        }
        return n == 0 ? flat : sb.toString().trim();
    }

    static List<String> listItems(String text) {
        List<String> items = new ArrayList<>();
        for (String line : text.split("\n")) {
            String t = line.trim();
            if (t.matches("^(\\d+\\.|[-*])\\s+.+")) items.add(t.replaceFirst("^(\\d+\\.|[-*])\\s+", ""));
        }
        return items;
    }

    @SuppressWarnings("unused")
    private static String money(BigDecimal v) {
        return INR.format(v);
    }
}
